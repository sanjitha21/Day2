#explain list of list with example
# A list of lists is a list where each element is itself a list. This allows for the creation of multi-dimensional data structures, such as matrices or grids.
# Example:
matrix = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9]
]
print(matrix)
#explain list of tuple with example
# A list of tuples is a list where each element is a tuple. Tuples are immutable sequences, and using them in a list allows for the storage of fixed-size collections of items.
# Example:  
list_of_tuples = [
    (1, 2, 3),
    (4, 5, 6),
    (7, 8, 9)
]
print(list_of_tuples)

#explain tuple of list with example
# A tuple of lists is a tuple where each element is a list. This allows for the creation of a fixed-size collection of lists, where the lists themselves can be modified.
# Example:  
tuple_of_lists = (
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9]
)
print(tuple_of_lists)